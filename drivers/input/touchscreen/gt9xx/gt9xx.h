struct goodix_ts_data {
	spinlock_t irq_lock;		/* offset 0 */
	struct i2c_client *client;	/* offset 8 */
	struct input_dev *input_dev;	/* offset 16 */
	struct hrtimer timer;		/* offset 24 */
	struct work_struct work;	/* offset 88 */
	int irq_is_disable;		/* offset 120 (0x78) */
	int use_irq;			/* offset 124 (0x7c) */
	u16 abs_x_max;			/* offset 128 */
	u16 abs_y_max;			/* offset 130 */
	u16 dummy1;			/* offset 132 */
	u8 int_trigger_type;		/* offset 134/133 */
	u8 dummy2;			/* offset 134 */
	u8 rawdiff_mode;		/* offset 135 */
	u8 is_suspended;		/* offset 136 */
	u8 dummy3;			/* offset 137 */
	u16 dummy4;			/* offset 138 */
	int cfg_len;			/* offset 140 */
	u8 fw_error;			/* offset 144 */
	u8 pnl_init_error;		/* offset 145 */
	u8 dummy5[6];			/* offset 146 */
	struct notifier_block fb_notif;	/* offset 152 (0x98) */
	struct input_dev *pen_dev;	/* offset 176 (0xb0) */
	spinlock_t esd_lock;		/* offset 184 (0xb8) */
	u8 esd_running;			/* offset 188 (0xbc) */
	u8 dummy6[3];			/* offset 189 */
	int clk_tick_cnt;		/* offset 192 (0xc0) */
	u8 dummy7[4];			/* total size 200 (0xc8) */
};

